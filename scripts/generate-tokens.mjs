// Generates src/styles/figma-tokens.css from design-tokens/figma-variables.json
// (an export of the TFI-Design Figma file's local variables and text styles).
// Run: node scripts/generate-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync(new URL("../design-tokens/figma-variables.json", import.meta.url), "utf8"));
const kebab = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const hex = ({ r, g, b, a = 1 }) => {
  const h = (x) => Math.round(x * 255).toString(16).padStart(2, "0");
  return a < 1 ? `rgba(${Math.round(r * 255)}, ${Math.round(g * 255)}, ${Math.round(b * 255)}, ${+a.toFixed(2)})` : `#${h(r)}${h(g)}${h(b)}`;
};
const value = (v, prefix = "") => (v && v.alias ? `var(--${prefix}${kebab(v.alias)})` : typeof v === "object" ? hex(v) : v);

const out = [
  "/* GENERATED by scripts/generate-tokens.mjs from design-tokens/figma-variables.json.",
  "   Do not edit by hand: change the Figma file, re-export, and re-run the script.",
  "   Names mirror the Figma variables (Content/Accent/Orange/Default → --content-accent-orange-default). */",
  "",
];
const light = [];
const dark = [];
let typeClasses = [];

for (const c of data) {
  if (c.collection === "Color Primitives") {
    light.push(`  /* Color Primitives */`);
    for (const v of c.vars) {
      const d = v.values.Default;
      light.push(`  --${kebab(v.name)}: ${v.type === "FLOAT" ? d / 100 : value(d)};`);
    }
  } else if (c.collection === "Color Semantic") {
    light.push(``, `  /* Color Semantic (Light) */`);
    dark.push(`  /* Color Semantic (Dark) */`);
    for (const v of c.vars) {
      light.push(`  --${kebab(v.name)}: ${value(v.values.Light)};`);
      dark.push(`  --${kebab(v.name)}: ${value(v.values.Dark)};`);
    }
  } else if (c.collection === "Spacing" || c.collection === "Radius") {
    const p = c.collection === "Spacing" ? "space" : "radius";
    light.push(``, `  /* ${c.collection} */`);
    for (const v of c.vars) light.push(`  --${p}-${kebab(v.name)}: ${v.values.Default}px;`);
  } else if (c.collection === "Text Styles") {
    const family = (f) => (f.includes("Display") ? "var(--font-display)" : f.includes("Mono") ? "var(--font-mono)" : "var(--font-sans)");
    const weight = (s) => ({ Regular: 400, Medium: 500, Semibold: 600, Bold: 700 })[s] ?? 400;
    typeClasses = c.textStyles.map((t) => {
      const [group, size] = t.name.split("/");
      const cls = group === "Heading" ? `t-${size.toLowerCase()}` : `t-${group.toLowerCase()}-${size.toLowerCase()}`;
      const lh = t.lineHeight.endsWith("%") ? parseFloat(t.lineHeight) / 100 : t.lineHeight;
      return `.${cls} { font-family: ${family(t.family)}; font-weight: ${weight(t.style)}; font-size: ${t.size}px; line-height: ${lh}; } /* ${t.name} */`;
    });
  }
}

out.push(":root {", ...light, "}", "");
out.push("/* Dark mode is imported but off: add data-theme=\"dark\" to <html> to switch it on. */");
out.push(":root[data-theme=\"dark\"] {", ...dark, "}", "");
out.push("/* Text styles */", ...typeClasses, "");
writeFileSync(new URL("../src/styles/figma-tokens.css", import.meta.url), out.join("\n"));
console.log(`figma-tokens.css: ${light.filter((l) => l.startsWith("  --")).length} tokens, ${dark.length - 1} dark overrides, ${typeClasses.length} text styles`);
